    /* =====================================================
       FIND SAFE ARTICLE POSITIONS
    ===================================================== */

    function getPositions(article) {

        const elements =
            article.querySelectorAll(
                "p, h2, h3, h4"
            );


        const positions = [];


        elements.forEach(
            element => {

                if (
                    isProtected(element)
                ) {
                    return;
                }


                if (
                    element.closest(
                        ".zm-ad"
                    )
                ) {
                    return;
                }


                const text =
                    element.innerText
                        ?.trim() || "";


                if (
                    element.tagName === "P" &&
                    text.length < 60
                ) {

                    return;

                }


                positions.push(
                    element
                );

            }
        );


        return positions;

    }


    /* =====================================================
       PLACE ADS
    ===================================================== */

    function placeAds() {

        const article =
            getArticle();


        if (!article) {
            return;
        }


        const positions =
            getPositions(
                article
            );


        if (!positions.length) {
            return;
        }


        const ads =
            shuffle(
                MANUAL_ADS
            );


        /*
         * Maximum 10 ads.
         */

        const total =
            Math.min(
                10,
                ads.length,
                positions.length
            );


        /*
         * Spread ads through article.
         */

        const step =
            positions.length /
            total;


        for (
            let i = 0;
            i < total;
            i++
        ) {

            const index =
                Math.floor(
                    i * step
                );


            const position =
                positions[index];


            if (
                !position ||
                isProtected(position)
            ) {
                continue;
            }


            const ad =
                createAd(
                    ads[i]
                );


            position.after(
                ad
            );

        }

    }


    /* =====================================================
       START
    ===================================================== */

    function start() {

        setTimeout(
            placeAds,
            800
        );

    }


    if (
        document.readyState ===
        "loading"
    ) {

        document.addEventListener(
            "DOMContentLoaded",
            start
        );

    } else {

        start();

    }

